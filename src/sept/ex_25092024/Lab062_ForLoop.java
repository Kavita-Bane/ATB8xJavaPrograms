package ex_25092024;

public class Lab062_ForLoop {
    public static void main(String[] args) {
        //Loops- to execute the same code multiple times
        //For , While , Do While
        //For Loop --
        // has 3 parts
        //int =1; - initialization (where to start)
        // i<=10; - condition where to terminate
        // i++ /i-- - Increment/decrement
        for(int i=1;i<=10;i++)
        {
            System.out.println(i);  //print 1 to 10 no's
        }
    }
}
